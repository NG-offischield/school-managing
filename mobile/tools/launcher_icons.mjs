// Android launcher icons of the four apps, drawn from the ISBREE monogram of the
// public site (web/isbree-public/src/components/logo.tsx: same paths, same colours).
//
//   node mobile/tools/launcher_icons.mjs        (from the repository root; offline)
//
// Writes, for each app (parent, teacher, staff, guardian):
//   res/mipmap-*/ic_launcher.png             legacy icon (Android < 8): ivory rounded square
//   res/mipmap-*/ic_launcher_foreground.png  adaptive icon foreground (Android 8+), 108 dp canvas,
//                                            artwork inside the 66 dp safe zone (never cropped)
//   res/mipmap-anydpi-v26/ic_launcher.xml    adaptive icon = ivory background + foreground
//   res/values/ic_launcher_background.xml    the background colour
// and web/isbree-portal/public/apps/<app>.png (the same icon on the portal's download card).
// The role is told by the colour of the ring (shared identity, distinct apps).
// Renders with the Chromium/Edge of Playwright, already installed for the web tests.
import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const { chromium } = createRequire(join(root, "web/isbree-public/package.json"))("@playwright/test");

const IVORY = "#faf6ee";
const APPS = {
  parent: "#2c6a4c", // forest
  teacher: "#a84a2a", // terracotta
  staff: "#d9a441", // ochre
  guardian: "#24456f", // ink
};
const MARK = `
  <path d="M6 60V30C6 15.6 17.6 4 32 4s26 11.6 26 26v30z" fill="#10294a"/>
  <path d="M11 60V30.5C11 18.9 20.4 9.5 32 9.5S53 18.9 53 30.5V60" fill="none" stroke="#d9a441" stroke-width="1.6"/>
  <circle cx="32" cy="29" r="10" fill="#d9a441"/>
  <path d="M32 47V24" stroke="#faf6ee" stroke-width="3.2" stroke-linecap="round"/>
  <path d="M32 33c-1-6.2-5.4-9.6-11.4-9.4.4 6.1 4.8 9.7 11.4 9.4z" fill="#3f8a63"/>
  <path d="M32 28.5c1-5.4 4.9-8.4 10.2-8.2-.4 5.4-4.3 8.5-10.2 8.2z" fill="#3f8a63"/>
  <path d="M12 49.5c6.8-2.6 13.5-2.4 20 1.3 6.5-3.7 13.2-3.9 20-1.3V56c-6.8-2.6-13.5-2.4-20 1.3-6.5-3.7-13.2-3.9-20-1.3z" fill="#faf6ee"/>
  <path d="M32 50.8v6.5" stroke="#10294a" stroke-width="1.2"/>`;

// 108 x 108 canvas (adaptive icon). Safe zone: circle of radius 33 around (54, 54).
const artwork = (accent) => `
  <circle cx="54" cy="54" r="30" fill="none" stroke="${accent}" stroke-width="3.5"/>
  <g transform="translate(54 54.5) scale(0.62) translate(-32 -32)">${MARK}</g>`;
const foreground = (accent) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">${artwork(accent)}</svg>`;
// Legacy icon: the 72 dp visible part of the same canvas, on an ivory rounded square.
const legacy = (accent) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72"><rect x="18" y="18" width="72" height="72" rx="16" fill="${IVORY}"/>${artwork(accent)}</svg>`;

const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };

const browser = await chromium.launch({ channel: process.env.E2E_BROWSER_CHANNEL || "msedge" });
const page = await browser.newPage();
async function png(svg, size, file) {
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(
    `<html><body style="margin:0;background:transparent">${svg.replace("<svg ", `<svg width="${size}" height="${size}" `)}</body></html>`,
  );
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, await page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: size, height: size } }));
}

for (const [app, accent] of Object.entries(APPS)) {
  const res = join(root, "mobile/apps", app, "android/app/src/main/res");
  for (const [density, scale] of Object.entries(DENSITIES)) {
    await png(legacy(accent), Math.round(48 * scale), join(res, `mipmap-${density}`, "ic_launcher.png"));
    await png(foreground(accent), Math.round(108 * scale), join(res, `mipmap-${density}`, "ic_launcher_foreground.png"));
  }
  mkdirSync(join(res, "mipmap-anydpi-v26"), { recursive: true });
  writeFileSync(
    join(res, "mipmap-anydpi-v26", "ic_launcher.xml"),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/tools/launcher_icons.mjs (ISBREE monogram). -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
`,
  );
  writeFileSync(
    join(res, "values", "ic_launcher_background.xml"),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/tools/launcher_icons.mjs. -->
<resources>
    <color name="ic_launcher_background">${IVORY}</color>
</resources>
`,
  );
  await png(legacy(accent), 192, join(root, "web/isbree-portal/public/apps", `${app}.png`));
  console.log(`${app}: icons written`);
}
await browser.close();
